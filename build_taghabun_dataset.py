def get_meta(surah_num, ayah_num):
    s = quran.get(str(surah_num))
    if not s:
        raise ValueError(f"Surah {surah_num} not found")
    for a in s['ayahs']:
        if a['numberInSurah'] == ayah_num:
            return a
    raise ValueError(f"Ayah {surah_num}:{ayah_num} not found")

def make_v(surah_num, ayah_num, tokens, html_span, custom_pos=None):
    a = get_meta(surah_num, ayah_num)
    s_name = SURAH_NAMES.get(surah_num, a.get('surahName', f'سورة {surah_num}'))
    raw_text = a['text']
    return {
        "surah": s_name,
        "surahName": f"سورة {s_name}",
        "ayah": ayah_num,
        "page": a.get('page', 556),
        "juz": a.get('juz', 28),
        "quarter": a.get('quarter', "الحزب 56 • الربع 3"),
        "pos": custom_pos if custom_pos else f"الآية {ayah_num}",
        "text": raw_text,
        "tokens": tokens,
        "html": html_span
    }

